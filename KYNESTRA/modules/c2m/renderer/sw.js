const CACHE = 'kynestra-c2m-pwa-v2';
const CORE = [
  './',
  './index.html',
  './media-stack.js',
  './manifest.webmanifest',
  './icons/icon.svg'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE)
      .then(cache => cache.addAll(CORE))
      .then(() => self.skipWaiting())
  );
});

